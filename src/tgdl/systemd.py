"""systemd integration: sd_notify (readiness, status, watchdog) and unit
file generation. No dependency: the notify protocol is a datagram on a
unix socket."""

from __future__ import annotations

import asyncio
import os
import shlex
import socket
import sys
from collections.abc import Callable
from pathlib import Path

from .config import AppConfig

# sysexits.h EX_CONFIG: configuration problem, restarting will not help.
EXIT_CONFIG = 78


def notify(state: str) -> bool:
    """Send ``state`` (e.g. "READY=1") to systemd. No-op outside systemd."""
    addr = os.environ.get("NOTIFY_SOCKET")
    if not addr:
        return False
    if addr.startswith("@"):  # abstract namespace
        addr = "\0" + addr[1:]
    try:
        with socket.socket(socket.AF_UNIX, socket.SOCK_DGRAM | socket.SOCK_CLOEXEC) as s:
            s.connect(addr)
            s.sendall(state.encode("utf-8"))
        return True
    except OSError:
        return False


def watchdog_interval() -> float | None:
    """Half the watchdog timeout systemd asked for, or None."""
    usec = os.environ.get("WATCHDOG_USEC")
    pid = os.environ.get("WATCHDOG_PID")
    if not usec or (pid and pid != str(os.getpid())):
        return None
    try:
        return max(1.0, int(usec) / 1_000_000 / 2)
    except ValueError:
        return None


async def watchdog_loop(status: Callable[[], str] | None = None) -> None:
    """Ping the watchdog from the event loop: if the loop hangs, the pings
    stop and systemd restarts the service. Also refreshes STATUS=."""
    interval = watchdog_interval() or 30.0
    enabled = watchdog_interval() is not None
    while True:
        parts = []
        if enabled:
            parts.append("WATCHDOG=1")
        if status is not None:
            parts.append(f"STATUS={status()}")
        if parts:
            notify("\n".join(parts))
        await asyncio.sleep(interval)


def under_systemd() -> bool:
    return bool(os.environ.get("INVOCATION_ID") or os.environ.get("NOTIFY_SOCKET"))


# ----------------------------------------------------------------- units
def _q(value: str | os.PathLike[str]) -> str:
    """Quote a path for a unit file (spaces etc.)."""
    s = os.fspath(value)
    return s if s and all(c.isalnum() or c in "/._-+@:" for c in s) else '"' + s.replace('"', '\\"') + '"'


def tgdl_executable() -> Path:
    """The tgdl entry point of the running installation (venv)."""
    exe = Path(sys.argv[0]).resolve() if sys.argv and sys.argv[0] else None
    if exe and exe.name == "tgdl" and exe.exists():
        return exe
    return Path(sys.executable).resolve().parent / "tgdl"


def render_unit(cfg: AppConfig, *, system: bool, user: str, lang: str,
                exe: Path | None = None) -> str:
    """A ready-to-install unit file for this installation."""
    exe = exe or tgdl_executable()
    home = cfg.home
    exec_start = " ".join([_q(exe), "--lang", shlex.quote(lang), "serve"])
    lines = [
        "# Generated by `tgdl systemd-unit`" + (" --system" if system else ""),
        "[Unit]",
        "Description=tgdl - Telegram media downloader",
        "Documentation=https://github.com/josch0510/josch_tgdl",
        "After=network-online.target",
    ]
    if system:
        lines.append("Wants=network-online.target")
    lines += [
        "",
        "[Service]",
        "Type=notify",
        "NotifyAccess=main",
    ]
    if system:
        lines += [f"User={user}", f"Group={user}"]
    lines += [
        f"WorkingDirectory={_q(home)}",
        f"Environment=TGDL_HOME={_q(home)}",
        "Environment=PYTHONUNBUFFERED=1",
        f"ExecStart={exec_start}",
        "# Connecting to Telegram can take a while; graceful stop removes/keeps .part files.",
        "TimeoutStartSec=180",
        "TimeoutStopSec=60",
        "WatchdogSec=120",
        "Restart=on-failure",
        "RestartSec=15",
        "# 78 = configuration problem (not logged in, bad .env): do not restart-loop.",
        f"RestartPreventExitStatus={EXIT_CONFIG}",
        "",
        "# Hardening",
        "NoNewPrivileges=yes",
        "LockPersonality=yes",
        "RestrictRealtime=yes",
        "RestrictSUIDSGID=yes",
        "SystemCallArchitectures=native",
        "RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6",
    ]
    if system:
        writable = [home, *cfg.allowed_base_dirs]
        lines += [
            "PrivateTmp=yes",
            "PrivateDevices=yes",
            "ProtectSystem=strict",
            "ProtectHome=read-only",
            "# tgdl may only write its own directory and the allowed download directories",
            "ReadWritePaths=" + " ".join(_q(p) for p in dict.fromkeys(writable)),
            "ProtectKernelTunables=yes",
            "ProtectKernelModules=yes",
            "ProtectKernelLogs=yes",
            "ProtectControlGroups=yes",
            "ProtectClock=yes",
            "ProtectHostname=yes",
            "RestrictNamespaces=yes",
            "CapabilityBoundingSet=",
            "AmbientCapabilities=",
        ]
    lines += [
        "",
        "[Install]",
        "WantedBy=" + ("multi-user.target" if system else "default.target"),
        "",
    ]
    return "\n".join(lines)
