class ServeClient(FakeTelegram):
    def __init__(self, authorized: bool = True) -> None:
        super().__init__()
        self.authorized = authorized
        self.disconnected = None

    async def connect(self):
        self.disconnected = asyncio.get_running_loop().create_future()

    async def is_user_authorized(self):
        return self.authorized

    async def get_me(self):
        return type("U", (), {"first_name": "t", "last_name": None})()

    async def disconnect(self):
        pass

    def add_event_handler(self, *a):
        pass

    def remove_event_handler(self, *a):
        pass


async def serve(tmp_path, monkeypatch, client) -> tuple[int, AppConfig]:
    import tgdl.telegram.client as tc
    from tgdl import app as appmod
    from tgdl.config import load_config
    (tmp_path / ".env").write_text(f"API_ID=1\nAPI_HASH=abcdef0123\nALLOWED_BASE_DIRS={tmp_path}/dl\n"
                                   "WEB_PORT=0\n")
    cfg = load_config(tmp_path)
    monkeypatch.setattr(tc, "build_client", lambda cfg, **kw: client)
    t = lambda k, **kw: k  # noqa: E731
    return await appmod.run_server(cfg, t, argparse.Namespace()), cfg


async def test_serve_lifecycle_with_systemd(tmp_path, monkeypatch, notify_socket) -> None:
    monkeypatch.setenv("WATCHDOG_USEC", "2000000")          # ping every second
    monkeypatch.setenv("WATCHDOG_PID", str(os.getpid()))
    task = asyncio.create_task(serve(tmp_path, monkeypatch, ServeClient()))
    msgs: list[str] = []
    for _ in range(100):
        msgs += received(notify_socket)
        if any(m.startswith("READY=1") for m in msgs) and any("WATCHDOG=1" in m for m in msgs):
            break
        await asyncio.sleep(0.05)
    assert msgs[0].startswith("READY=1\nSTATUS=monitors 0/0, downloading 0/3")
    os.kill(os.getpid(), signal.SIGTERM)                  # what `systemctl stop` sends
    rc, _ = await asyncio.wait_for(task, 15)
    msgs += received(notify_socket)
    assert rc == 0 and any(m.startswith("STOPPING=1") for m in msgs)


async def test_serve_not_logged_in_exits_78(tmp_path, monkeypatch, notify_socket) -> None:
    rc, _ = await serve(tmp_path, monkeypatch, ServeClient(authorized=False))
    assert rc == systemd.EXIT_CONFIG
    assert not any(m.startswith("READY=1") for m in received(notify_socket))


def test_console_log_format_under_journald(tmp_path, monkeypatch, capsys) -> None:
    import logging

    from tgdl.logging_setup import log_event, setup_logging
    monkeypatch.setenv("JOURNAL_STREAM", "8:1234")
    setup_logging(tmp_path / "logs", console=True)
    log_event(logging.getLogger("tgdl.t"), logging.INFO, "probe", "hello")
    line = capsys.readouterr().err.strip().splitlines()[-1]
    assert line.startswith("INFO | ") and "action=probe" in line      # no timestamp for journald
    file_line = (tmp_path / "logs" / "tgdl.log").read_text().strip().splitlines()[-1]
    assert file_line[:4].isdigit() and "action=probe" in file_line   # file keeps timestamps
    monkeypatch.delenv("JOURNAL_STREAM")
    setup_logging(tmp_path / "logs", console=False)


async def test_second_instance_refused(tmp_path, monkeypatch) -> None:
    from tgdl.app import acquire_instance_lock
    from tgdl.config import load_config
    (tmp_path / ".env").write_text(f"ALLOWED_BASE_DIRS={tmp_path}/dl\n")
    cfg = load_config(tmp_path)
    first = acquire_instance_lock(cfg)
    assert first is not None
    import subprocess
    import sys
    code = ("import sys\nfrom pathlib import Path\nfrom tgdl.config import load_config\n"
            "from tgdl.app import acquire_instance_lock\n"
            "print(acquire_instance_lock(load_config(Path(sys.argv[1]))) is None)\n")
    r = subprocess.run([sys.executable, "-c", code, str(tmp_path)], capture_output=True, text=True, timeout=20)
    assert r.stdout.strip() == "True"                      # another process is refused
    first.close()                                          # released -> available again
    r = subprocess.run([sys.executable, "-c", code, str(tmp_path)], capture_output=True, text=True, timeout=20)
    assert r.stdout.strip() == "False"
