@pytest.fixture
def notify_socket(tmp_path, monkeypatch):
    path = tmp_path / "notify.sock"
    sock = socket.socket(socket.AF_UNIX, socket.SOCK_DGRAM)
    sock.bind(str(path))
    sock.setblocking(False)
    monkeypatch.setenv("NOTIFY_SOCKET", str(path))
    yield sock
    sock.close()


def received(sock) -> list[str]:
    out = []
    while True:
        try:
            out.append(sock.recv(4096).decode())
        except BlockingIOError:
            return out


def test_notify(notify_socket) -> None:
    assert systemd.notify("READY=1\nSTATUS=ok")
    assert received(notify_socket) == ["READY=1\nSTATUS=ok"]


def test_notify_outside_systemd(monkeypatch) -> None:
    monkeypatch.delenv("NOTIFY_SOCKET", raising=False)
    assert systemd.notify("READY=1") is False


def test_watchdog_interval(monkeypatch) -> None:
    monkeypatch.delenv("WATCHDOG_USEC", raising=False)
    assert systemd.watchdog_interval() is None
    monkeypatch.setenv("WATCHDOG_USEC", "120000000")
    monkeypatch.setenv("WATCHDOG_PID", str(os.getpid()))
    assert systemd.watchdog_interval() == 60
    monkeypatch.setenv("WATCHDOG_PID", "1")  # meant for another process
    assert systemd.watchdog_interval() is None


def make_cfg(tmp_path, *roots) -> AppConfig:
    return AppConfig(home=tmp_path / "my tgdl", api_id=1, api_hash="x" * 32,
                     allowed_base_dirs=tuple(roots) or (tmp_path / "dl",))


def test_user_unit(tmp_path) -> None:
    unit = systemd.render_unit(make_cfg(tmp_path), system=False, user="josch", lang="zh-TW",
                               exe=Path("/home/josch/tgdl/.venv/bin/tgdl"))
    assert "Type=notify" in unit and "WatchdogSec=" in unit
    assert "ExecStart=/home/josch/tgdl/.venv/bin/tgdl --lang zh-TW serve" in unit
    assert f'WorkingDirectory="{tmp_path / "my tgdl"}"' in unit      # path with a space quoted
    assert "RestartPreventExitStatus=78" in unit
    assert "User=" not in unit and "WantedBy=default.target" in unit


def test_system_unit(tmp_path) -> None:
    unit = systemd.render_unit(make_cfg(tmp_path, Path("/srv/media"), Path("/data/tg")),
                               system=True, user="josch", lang="en", exe=Path("/opt/tgdl/bin/tgdl"))
    assert "User=josch" in unit and "Group=josch" in unit and "WantedBy=multi-user.target" in unit
    assert "ProtectSystem=strict" in unit and "ProtectHome=read-only" in unit
    rw = [line for line in unit.splitlines() if line.startswith("ReadWritePaths=")][0]
    assert "/srv/media" in rw and "/data/tg" in rw and "my tgdl" in rw


